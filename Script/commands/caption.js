// ============ ক্যাপশন শেষ ============

// প্রতি ইউজারের শেষ ক্যাপশন (একই ক্যাপশন পরপর আসবে না)
const lastUsed = {};

// প্রতি ইউজারের লিমিট ট্র্যাক (১ ঘন্টায় ১০টি)
const userLimit = {};

// ============ কনফিগারেশন ============
const CONFIG = {
  MAX_PER_HOUR: 10,        // ১ ঘন্টায় সর্বোচ্চ ১০টি
  ONE_HOUR: 60 * 60 * 1000, // ১ ঘন্টা = ৩৬০০০০০ ms
  TOP_RANGE: 20,           // প্রথম ২০টা ক্যাপশন বেশি আসবে
  TOP_WEIGHT: 70           // ৭০% সম্ভাবনা প্রথম ২০টা থেকে আসবে
};

/**
 * র‍্যান্ডম ক্যাপশন বের করার ফাংশন
 * ১-২০ নম্বর ক্যাপশন বেশি আসবে (৭০%)
 */
function getRandomCaption(userID) {
  let idx, tries = 0;

  do {
    // ৭০% সম্ভাবনা → ১-২০ থেকে, ৩০% → ২১-৪৯ থেকে
    if (Math.random() * 100 < CONFIG.TOP_WEIGHT) {
      idx = Math.floor(Math.random() * CONFIG.TOP_RANGE); // ০-১৯ (১-২০ নম্বর)
    } else {
      idx = CONFIG.TOP_RANGE + Math.floor(Math.random() * (tl.length - CONFIG.TOP_RANGE));
    }
    tries++;
  } while (idx === lastUsed[userID] && tries < 10);

  lastUsed[userID] = idx;
  return tl[idx];
}

/**
 * লিমিট চেক করার ফাংশন
 */
function checkLimit(userID) {
  const now = Date.now();
  const userData = userLimit[userID];

  // প্রথমবার কেউ ক্যাপশন নিচ্ছে
  if (!userData) {
    userLimit[userID] = {
      count: 1,
      firstTime: now
    };
    return { allowed: true, remaining: CONFIG.MAX_PER_HOUR - 1 };
  }

  // ১ ঘন্টা পার হয়ে গেলে রিসেট
  if (now - userData.firstTime >= CONFIG.ONE_HOUR) {
    userLimit[userID] = {
      count: 1,
      firstTime: now
    };
    return { allowed: true, remaining: CONFIG.MAX_PER_HOUR - 1 };
  }

  // লিমিট শেষ?
  if (userData.count >= CONFIG.MAX_PER_HOUR) {
    const timeLeft = CONFIG.ONE_HOUR - (now - userData.firstTime);
    const minutesLeft = Math.ceil(timeLeft / 60000);
    return {
      allowed: false,
      remaining: 0,
      minutesLeft: minutesLeft
    };
  }

  // লিমিট বাড়াও
  userData.count++;
  return {
    allowed: true,
    remaining: CONFIG.MAX_PER_HOUR - userData.count
  };
}

// ============ কমান্ড রান ============
module.exports.run = async function ({ api, event }) {
  const { threadID, messageID, senderID } = event;

  // লিমিট চেক
  const limitCheck = checkLimit(senderID);

  // যদি লিমিট শেষ হয়ে যায়
  if (!limitCheck.allowed) {
    return api.sendMessage(
      `⏳ আপনি ১ ঘন্টায় সর্বোচ্চ ${CONFIG.MAX_PER_HOUR}টি ক্যাপশন নিতে পারবেন।\n\n` +
      `🕐 পরের ক্যাপশন পেতে অপেক্ষা করুন: ${limitCheck.minutesLeft} মিনিট`,
      threadID,
      messageID
    );
  }

  // র‍্যান্ডম ক্যাপশন
  const caption = getRandomCaption(senderID);

  // ক্যাপশন পাঠাও
  return api.sendMessage(caption, threadID, messageID);
};
